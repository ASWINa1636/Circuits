package com.example.circuits

import android.os.Bundle
import android.widget.ArrayAdapter
import android.widget.Button
import android.widget.EditText
import android.widget.Spinner
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import com.example.circuits.data.User
import com.example.circuits.db.DatabaseHelper
import android.util.Log // Import Log

class SignupActivity : AppCompatActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_signup)

        // Find UI elements
        val etName = findViewById<EditText>(R.id.etSignupName)
        val etUsername = findViewById<EditText>(R.id.etSignupUsername)
        val etEmail = findViewById<EditText>(R.id.etSignupEmail)
        val etPassword = findViewById<EditText>(R.id.etSignupPassword)
        val spinnerProfile = findViewById<Spinner>(R.id.spinnerProfileType)
        val btnSignup = findViewById<Button>(R.id.btnSignup)
        val db = DatabaseHelper(this)

        // Setup Spinner
        ArrayAdapter.createFromResource(
            this,
            R.array.profile_types_array, // Ensure this array exists in strings.xml
            android.R.layout.simple_spinner_item
        ).also { adapter ->
            // Specify the layout to use when the list of choices appears
            adapter.setDropDownViewResource(android.R.layout.simple_spinner_dropdown_item)
            // Apply the adapter to the spinner
            spinnerProfile.adapter = adapter
        }

        // Handle Signup Button Click
        btnSignup.setOnClickListener {
            // Get text from input fields
            val name = etName.text.toString().trim()
            val username = etUsername.text.toString().trim()
            val email = etEmail.text.toString().trim()
            val password = etPassword.text.toString() // Keep password as entered
            val profileType = spinnerProfile.selectedItem.toString()

            // Input Validation
            if (name.isEmpty() || username.isEmpty() || email.isEmpty() || password.isEmpty()) {
                Toast.makeText(this, R.string.error_fill_all_fields, Toast.LENGTH_SHORT).show()
                return@setOnClickListener
            }

            // More specific validation (e.g., email format) could be added here
            if (!android.util.Patterns.EMAIL_ADDRESS.matcher(email).matches()) {
                Toast.makeText(this, R.string.error_invalid_email, Toast.LENGTH_SHORT).show()
                return@setOnClickListener
            }

            // Check if a valid profile type is selected
            val selectProfileString = getString(R.string.select_profile_type_prompt) // Get prompt from strings.xml
            if (profileType == selectProfileString) {
                Toast.makeText(this, R.string.error_select_profile_type, Toast.LENGTH_SHORT).show()
                return@setOnClickListener
            }

            // Create User object (excluding password)
            // Note: In a real app, hash the password before saving!
            val user = User(
                id = 0, // ID will be auto-generated by the database
                fullName = name,
                username = username,
                email = email,
                profileType = profileType
            )

            // Attempt to add the user to the database, passing password separately
            val success = db.addUser(user, password)

            // Provide feedback based on success or failure
            if (success) {
                Log.d("SignupActivity", "User signup successful: ${user.username}")
                Toast.makeText(this, R.string.signup_successful, Toast.LENGTH_SHORT).show()
                finish() // Close SignupActivity and return to LoginActivity
            } else {
                Log.w("SignupActivity", "User signup failed (username or email might exist): ${user.username} / ${user.email}")
                Toast.makeText(this, R.string.error_user_exists, Toast.LENGTH_SHORT).show()
            }
        }
    }
}

